def _case(
    m: int,
    n: int,
    k: int,
    output_slice: bool = False,
    force_m_kernel: bool = False,
):
    assert k % 256 == 0
    generator = torch.Generator().manual_seed(20260910 + m + n + k)
    groups4 = k // 4
    group_ids = torch.arange(groups4, dtype=torch.int64).view(1, -1)
    row_ids = torch.arange(n, dtype=torch.int64).view(-1, 1)
    indices = (group_ids * 17 + row_ids * 37 + 11) % 512
    qs = indices.to(torch.uint8).contiguous()
    high = (indices >> 8).to(torch.uint8).reshape(n, -1, 8)
    qh = (high << torch.arange(8, dtype=torch.uint8).view(1, 1, 8)).sum(
        dim=2
    ).to(torch.uint8).contiguous()

    element_ids = torch.arange(k, dtype=torch.int64).view(1, -1)
    negative = ((element_ids * 13 + row_ids * 7 + 3) % 5 == 0).to(torch.uint8)
    signs = (
        negative.reshape(n, -1, 8)
        << torch.arange(8, dtype=torch.uint8).view(1, 1, 8)
    ).sum(dim=2).to(torch.uint8).contiguous()

    scale = (
        torch.rand((n, k // 32), generator=generator) * 0.008 + 0.0002
    ).to(torch.float16)
    x = torch.randn((m, k), generator=generator, dtype=torch.float16) * 0.25

    lut = torch.tensor(IQ3_GRID_PACKED, dtype=torch.int32)
    packed = lut[indices]
    magnitudes = torch.stack(
        tuple(((packed >> (4 * field)) & 15) for field in range(4)), dim=-1
    ).reshape(n, k).float()
    dense = magnitudes * (1.0 - 2.0 * negative.float())
    dense = (dense.reshape(n, k // 32, 32) * scale.float().unsqueeze(-1)).reshape(
        n, k
    )
    expected = (x.float() @ dense.t()).to(torch.float16)

    x_xpu = x.to("xpu")
    qs_xpu = qs.to("xpu")
    qh_xpu = qh.to("xpu")
    signs_xpu = signs.to("xpu")
    scale_xpu = scale.to("xpu")
    if output_slice:
        storage = torch.full(
            (m, n + 11), -123.0, dtype=torch.float16, device="xpu"
        )
        output = storage[:, 3 : 3 + n]
        if m == 1:
            assert output.is_contiguous()
        else:
            assert not output.is_contiguous()
    else:
        storage = None
        output = torch.empty((m, n), dtype=torch.float16, device="xpu")

    if m == 1 and not force_m_kernel:
        esimd_gemv_iq3_s(
            x_xpu, qs_xpu, qh_xpu, signs_xpu, scale_xpu, output
        )
    else:
        esimd_gemv_iq3_s_m(
            x_xpu, qs_xpu, qh_xpu, signs_xpu, scale_xpu, output
        )
    torch.xpu.synchronize()
    torch.testing.assert_close(output.cpu(), expected, rtol=0, atol=0.01)
    if storage is not None:
        host_storage = storage.cpu()
        assert torch.all(host_storage[:, :3] == -123)
        assert torch.all(host_storage[:, 3 + n :] == -123)


@pytest.mark.parametrize("m", [1, 2, 4, 8, 16])
@pytest.mark.parametrize("k", [256, 512, 5120])
def test_iq3_s_gemv_fixed_tiles(m, k):
    _case(m, n=37, k=k)


@pytest.mark.parametrize("m", [3, 17])
def test_iq3_s_gemv_arbitrary_m(m):
    _case(m, n=19, k=512)


@pytest.mark.parametrize("m", [1, 3, 4, 17])
def test_iq3_s_gemv_output_slice(m):
    _case(m=m, n=33, k=512, output_slice=True)


def test_iq3_s_gemv_m_accepts_single_input():
    _case(m=1, n=29, k=512, force_m_kernel=True)


def test_iq3_s_gemv_rejects_invalid_wrapper_arguments():
    m, n, k = 1, 7, 256
    x = torch.zeros((m, k), dtype=torch.float16, device="xpu")
    qs = torch.zeros((n, k // 4), dtype=torch.uint8, device="xpu")
    qh = torch.zeros((n, k // 32), dtype=torch.uint8, device="xpu")
    signs = torch.zeros((n, k // 8), dtype=torch.uint8, device="xpu")
    scale = torch.ones((n, k // 32), dtype=torch.float16, device="xpu")
    output = torch.empty((m, n), dtype=torch.float16, device="xpu")

    with pytest.raises(RuntimeError, match="invalid signs shape"):
        esimd_gemv_iq3_s(x, qs, qh, signs[:, :-1].contiguous(), scale, output)
    with pytest.raises(RuntimeError, match="must be uint8"):
        esimd_gemv_iq3_s(x, qs, qh.to(torch.float16), signs, scale, output)
    strided_output = torch.empty((m, n * 2), dtype=torch.float16, device="xpu")[
        :, ::2
    ]
    with pytest.raises(RuntimeError, match="contiguous rows"):
        esimd_gemv_iq3_s(x, qs, qh, signs, scale, strided_output)
